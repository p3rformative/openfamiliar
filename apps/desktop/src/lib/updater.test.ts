import assert from "node:assert/strict";
import { describe, it } from "node:test";
import { UPDATER_UNAVAILABLE_MESSAGE, mapUpdaterError } from "./updater";

describe("mapUpdaterError", () => {
  it("treats an empty-endpoints error as an inert channel", () => {
    assert.equal(
      mapUpdaterError("Updater does not have any endpoints set."),
      UPDATER_UNAVAILABLE_MESSAGE,
    );
    assert.equal(
      mapUpdaterError("  Updater does not have any endpoints set.  "),
      UPDATER_UNAVAILABLE_MESSAGE,
    );
  });

  it("keeps signature, network, and other failures visible", () => {
    assert.equal(
      mapUpdaterError("network failure"),
      "No se pudo buscar actualizaciones: network failure",
    );
    assert.equal(
      mapUpdaterError("The signature verification failed"),
      "No se pudo buscar actualizaciones: The signature verification failed",
    );
    assert.equal(
      mapUpdaterError(
        "The signature abc could not be decoded, please check if it is a valid base64 string. The signature must be the contents of the `.sig` file generated by the Tauri bundler, as a string.",
      ),
      "No se pudo buscar actualizaciones: The signature abc could not be decoded, please check if it is a valid base64 string. The signature must be the contents of the `.sig` file generated by the Tauri bundler, as a string.",
    );
    assert.equal(
      mapUpdaterError("Invalid encoding in minisign data"),
      "No se pudo buscar actualizaciones: Invalid encoding in minisign data",
    );
    assert.equal(
      mapUpdaterError("Could not decode public key"),
      "No se pudo buscar actualizaciones: Could not decode public key",
    );
  });
});
